void ProcessPacket(uint8_t *data,uint8_t len){
	extern UART_HandleTypeDef huart1;
	uint8_t SensorID=data[0];
	char msg[100];
	switch(SensorID){
		case 0x01:
			sprintf(msg,"[SpO2_BPM] SpO2:%d BPM:%d\r\n",data[1],data[2]);
			break;
		case 0x02:
			sprintf(msg, "[TEMP] Temp:%d C\r\n",data[1]);
			break;
	    case 0x03:    // Accelerometer
			sprintf(msg, "[ACCEL] X:%d Y:%d Z:%d\r\n",data[1], data[2], data[3]);
			break;
	    default:
			sprintf(msg, "[UNKNOWN_SENSOR] ID:0x%02X\r\n", SensorID);
			break;
	}
	HAL_UART_Transmit(&huart1,(uint8_t*)msg,strlen(msg),100);
}
